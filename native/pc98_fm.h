/* PC-98 の FM 音源で起動画面の曲を鳴らす層。
 *
 * ★叩くのは PC-9801-26K 相当（YM2203 = OPN）の範囲だけ: ポート 0188h（番地）/ 018Ah（値）の FM 3 声。
 *   PC-9801-86（YM2608 = OPNA）も同じポートで 26K 互換に鳴るので、どちらでも同じに鳴る。
 *   ボードが無ければ（0188h が FFh）何もしない。
 * ★割り込みは使わない。曲は music_poll() を呼んだときだけ進み、拍は垂直帰線（約 56.4 Hz）で数える。
 *   だからキーを待つ間に呼び続ける（起動画面の kbd_get の前）。
 * ★ホスト（PC98_HOST）では何もしない。
 */
#ifndef PC98_FM_H
#define PC98_FM_H

void music_start(void);                /* 音源があれば頭から鳴らし始める */
void music_poll(void);                 /* 次の垂直帰線を越えていたら曲を進める。何度呼んでもよい */
void music_stop(void);                 /* 音を止める（DOS へ返る前・起動画面を抜けるとき） */

#endif
