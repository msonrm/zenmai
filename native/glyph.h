/* Zenmai 字の境界。
 *
 * ★**この 5 本だけが「字がどう出るか」を知っている。** 組版・折返し・履歴・表示窓
 *   （render.c）は、幅を訊いて描けと言うだけで、字形の出どころを知らない。
 *
 * 実装は 1 つだけリンクする:
 *   glyph_baked.c … 焼いたビットマップ（glyphs.h）。PS1 と、★PS1 との画素一致を
 *                   確かめる SDL ビルド（test-sdl.sh）が使う
 *   glyph_ft.c    … FreeType。配布用の SDL ビルドが使う。字が増える（4 言語）・
 *                   プロポーショナルになる・拡縮が効く
 *
 * ★これは plat.h と同じ形の 2 本目の境界。plat.h が「機械」を切り出したのに対し、
 *   こちらは「字」を切り出す。どちらも上の層は無改造で載る。
 *
 * ★**背景色は渡さない。** アンチエイリアスは**描画先の画素に混ぜる**ことで解決する
 *   ので、本文・ルビ帯・オプションの藍板のどこに描いても正しく乗る。
 *   （引数に背景色を足すと、呼ぶ側が「いまどの地色の上か」を知る責任を負ってしまう）
 */
#ifndef GLYPH_H
#define GLYPH_H
#include <stdint.h>
#include "plat.h"

void glyph_init(void);                 /* 焼いた版は何もしない。FreeType 版は面を開く */
/* ★この実装がどのフォントで描いているか。ライセンス頁の帰属をここで切り替える ——
   ★**使っていないフォントの名を出すのは嘘**なので、字の出どころを知っている
   この層が名乗るのが正しい（実機の指摘・2026-08-30）。
   1 = 焼いたビットマップ（KH ドットフォント） / 2 = FreeType（同梱の Noto） */
int  glyph_font_kind(void);
void glyph_clip(int y0, int y1);       /* 描く行の範囲 [y0,y1)。外は捨てる */
int  glyph_w(uint16_t code);           /* 送り幅（px） */
/* ★rows = 描画先の**行数**。省略できない引数にしてある ——
   焼いたビットマップは必ず 24 行に収まるので要らなかったが、FreeType の
   descender（g / j / p / 読点）は**ベースラインより下**へ出るので、
   24 行の器（コマンド欄 strip[24] / 状態行 sbar[24]）に描くと
   ★**.bss の隣の変数を踏み潰す**。2026-08-30 に実機で発覚した——
   症状は「打った覚えのない字がコマンドに混じる」「フリーズ」「強制終了」で、
   メモリ破壊なので出方がランダムだった。
   ★build_strip には横方向の門（「draw24 は範囲を見ない」）が既にあったが、
   縦方向には無かった。**器の高さを渡さないと描けない形**にして塞ぐ。 */
void draw24(uint16_t (*buf)[W], int rows, int x, int y, uint16_t code, uint16_t color);
void draw12(uint16_t (*buf)[W], int rows, int x, int y, uint16_t code, uint16_t color);

/* ---- 整形（shaping）----
 *
 * ★**なぜ「幅を訊いて 1 字ずつ描く」では足りないか** —— デーヴァナーガリー
 *   （ヒンディー語）は母音記号が**論理の順と違う位置**へ回り（`ि` は子音の前に出る）、
 *   子音が**縦に積んで合字になる**（`क` + `्` + `ष` → `क्ष`）。
 *   ★**字の並びと画の並びが 1 対 1 でない**ので、`draw24(code)` をどう並べても
 *   正しい絵にならない。日本語・韓国語・英語で足りていたのは、たまたま 1 対 1 だから。
 *
 * ★★**cluster を返すのは、幅だけでは組めないから** —— 未確定の下線は
 *   「**この 1 字の下**に引く」形、キャレットの左右移動は「**論理の 1 字ぶん**動く」形。
 *   どちらも**論理の位置 ↔ 画の位置**の対応を要求する。合字と入れ替えが起きると
 *   これが自明でなくなるので、整形した側が対応を返すしかない。
 *
 * 実装は 2 つある:
 *   1 code = 1 glyph … 焼いたビットマップ（glyph_baked.c）と、いまの FreeType 版。
 *                      ★**日本語・韓国語・英語はこれで正しい**
 *   HarfBuzz         … デーヴァナーガリーを積むとき、FreeType 版だけが持つ。
 *                      ★PS1 には載らないので、**焼いた版は永久に 1 対 1 のまま**
 */
typedef struct {
    uint16_t gid;      /* 面の中のグリフ番号。★1 対 1 の実装では code そのもの */
    uint16_t cluster;  /* 元の列での位置。★下線とキャレットが要る */
    int16_t  adv;      /* 送り幅 */
    int8_t   dx, dy;   /* 描く位置の補正（母音記号の載せ替え） */
} Shaped;

/* s[0..n) を整形して out へ。戻り値 = 書いた数（max で打ち切る）。
   ★**行 1 本を丸ごと渡すこと。** 1 字ずつ呼ぶと合字も入れ替えも起きない ——
   呼んだ側は「動いている」と思うので、★**黙って間違った絵になる**。 */
int shape_run(const uint16_t *s, int n, Shaped *out, int max);

/* draw24 のグリフ番号版。★1 対 1 の実装では draw24 と同じものを描く。
   ★**draw24 を消さない**のは、ルビの親字・行インジケータ・記号のように
   **整形の要らない 1 字**を描く口が残るから（そこへ Shaped を通すのは遠回り）。 */
void draw24_gid(uint16_t (*buf)[W], int rows, int x, int y, uint16_t gid, uint16_t color);

#endif
